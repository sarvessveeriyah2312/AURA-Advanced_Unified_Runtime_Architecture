import { motion } from "framer-motion";
import type { ReactNode } from "react";

// Reveal fades content up once when it scrolls into view. MotionConfig in
// App sets reducedMotion="user", so this is skipped for visitors who
// prefer reduced motion.
export function Reveal({
  children,
  className,
  delay = 0,
}: {
  children: ReactNode;
  className?: string;
  delay?: number;
}) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y: 14 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-60px" }}
      transition={{ duration: 0.5, ease: [0.22, 1, 0.36, 1], delay }}
    >
      {children}
    </motion.div>
  );
}
